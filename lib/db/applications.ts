// Rate-limit log for mail sent to strangers; only a hash of the address.
export const applicationMailLog = pgTable(
  "application_mail_log",
  {
    id: bigint({ mode: "number" }).primaryKey().generatedAlwaysAsIdentity(),
    recipientHash: text().notNull(),
    kind: text().notNull(),
    createdAt: timestamp({ withTimezone: true }).notNull(),
  },
  (table) => [
    check(
      "application_mail_log_recipient_hash",
      matches("recipient_hash", TOKEN_HASH_PATTERN)
    ),
    check("application_mail_log_kind", oneOf("kind", ANONYMOUS_MAIL_KINDS)),
    index("application_mail_log_recipient").on(
      table.recipientHash,
      table.createdAt
    ),
    index("application_mail_log_created").on(table.createdAt),
  ]
)

