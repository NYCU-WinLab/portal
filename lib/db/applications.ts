// Same shape as admins_app_known: a CHECK listing the allowed values.
const list = (values: readonly string[]) =>
  values.map((value) => `'${value}'`).join(", ")

const oneOf = (column: string, values: readonly string[]) =>
  sql.raw(`${column} in (${list(values)})`)

const matches = (column: string, pattern: string) =>
  sql.raw(`${column} ~ '${pattern}'`)

const lengthBetween = (column: string, max: number) =>
  sql.raw(`char_length(${column}) between 1 and ${max}`)

// Time columns carry no default: the caller passes the time in, so a test can
// fix it. Only ids (gen_random_uuid, identity) are generated by Postgres.

// One row per application. Personal data lives in lab_application_profiles and
// is erased on purge; this row keeps the decision and its dates.
export const labApplications = pgTable(
  "lab_applications",
  {
    id: uuid().defaultRandom().primaryKey(),
    status: text().notNull().default("unverified"),
    version: integer().notNull().default(1),
    email: text(),
    requestedStatus: text().notNull(),
    assignedStatus: text(),
    assignedCohort: integer(),
    assignedUsername: text(),
    reviewedBy: uuid().references(() => user.id, { onDelete: "set null" }),
    reviewedAt: timestamp({ withTimezone: true }),
    reviewNote: text(),
    keycloakId: uuid(),
    createdAt: timestamp({ withTimezone: true }).notNull(),
    verifiedAt: timestamp({ withTimezone: true }),
    closedAt: timestamp({ withTimezone: true }),
    purgedAt: timestamp({ withTimezone: true }),
  },
  (table) => [
    check("lab_applications_version", sql`${table.version} >= 1`),
    check(
      "lab_applications_requested_status",
      oneOf("requested_status", REQUESTED_STATUSES)
    ),
    check(
      "lab_applications_assigned_status",
      oneOf("assigned_status", LAB_STATUSES)
    ),
    check(
      "lab_applications_assigned_cohort",
      sql.raw(
        `assigned_cohort between ${COHORT_RANGE[0]} and ${COHORT_RANGE[1]}`
      )
    ),
    check(
      "lab_applications_assigned_username",
      matches("assigned_username", USERNAME_PATTERN)
    ),
    check("lab_applications_status", oneOf("status", APPLICATION_STATUSES)),
    check(
      "lab_applications_email",
      sql`${table.email} = lower(${table.email}) and (${table.email} is not null or ${table.purgedAt} is not null)`
    ),
    check(
      "lab_applications_verified",
      sql`(${table.status} = 'unverified') = (${table.verifiedAt} is null)`
    ),
    check(
      "lab_applications_closed",
      sql.raw(
        `(status in (${list(CLOSED_STATUSES)})) = (closed_at is not null)`
      )
    ),
    check(
      "lab_applications_decided",
      sql`${table.status} not in ('provisioning', 'accepted') or (${table.assignedStatus} is not null and ${table.assignedCohort} is not null and ${table.assignedUsername} is not null and ${table.reviewedAt} is not null)`
    ),
    check(
      "lab_applications_account",
      sql`${table.status} <> 'accepted' or ${table.keycloakId} is not null`
    ),
    check(
      "lab_applications_purged",
      sql`${table.purgedAt} is null or (${table.closedAt} is not null and ${table.email} is null and ${table.reviewNote} is null)`
    ),
    uniqueIndex("lab_applications_active_email")
      .on(table.email)
      .where(sql.raw(`status in (${list(ACTIVE_STATUSES)})`)),
    uniqueIndex("lab_applications_unverified_email")
      .on(table.email)
      .where(sql`${table.status} = 'unverified'`),
    uniqueIndex("lab_applications_claimed_username")
      .on(table.assignedUsername)
      .where(sql`${table.status} = 'provisioning'`),
    index("lab_applications_open")
      .on(table.status, table.createdAt)
      .where(sql`${table.closedAt} is null`),
    index("lab_applications_by_email")
      .on(table.email, table.createdAt)
      .where(sql`${table.email} is not null`),
    index("lab_applications_closed_at")
      .on(table.closedAt)
      .where(sql`${table.closedAt} is not null`),
  ]
)

// What the applicant typed. Deleted with the personal data on purge.
export const labApplicationProfiles = pgTable(
  "lab_application_profiles",
  {
    applicationId: uuid()
      .primaryKey()
      .references(() => labApplications.id, { onDelete: "cascade" }),
    username: text().notNull(),
    chineseName: text().notNull(),
    firstName: text().notNull(),
    lastName: text().notNull(),
    studentId: text(),
    birthday: date({ mode: "string" }).notNull(),
    phone: text().notNull(),
    nycuEmail: text(),
    department: text().notNull(),
    lineId: text().notNull(),
    updatedAt: timestamp({ withTimezone: true }).notNull(),
  },
  () => [
    check(
      "lab_application_profiles_username",
      matches("username", USERNAME_PATTERN)
    ),
    check(
      "lab_application_profiles_chinese_name",
      lengthBetween("chinese_name", LIMITS.chineseName)
    ),
    check(
      "lab_application_profiles_first_name",
      lengthBetween("first_name", LIMITS.firstName)
    ),
    check(
      "lab_application_profiles_last_name",
      lengthBetween("last_name", LIMITS.lastName)
    ),
    check(
      "lab_application_profiles_student_id",
      lengthBetween("student_id", LIMITS.studentId)
    ),
    check(
      "lab_application_profiles_birthday",
      sql.raw(
        `birthday between '${BIRTHDAY_RANGE[0]}' and '${BIRTHDAY_RANGE[1]}'`
      )
    ),
    check("lab_application_profiles_phone", matches("phone", PHONE_PATTERN)),
    check(
      "lab_application_profiles_nycu_email",
      sql.raw(
        `nycu_email = lower(nycu_email) and char_length(nycu_email) <= ${LIMITS.email}`
      )
    ),
    check(
      "lab_application_profiles_department",
      lengthBetween("department", LIMITS.department)
    ),
    check(
      "lab_application_profiles_line_id",
      lengthBetween("line_id", LIMITS.lineId)
    ),
  ]
)

// Only the SHA-256 of a link token is stored; one token per purpose.
export const labApplicationTokens = pgTable(
  "lab_application_tokens",
  {
    applicationId: uuid()
      .notNull()
      .references(() => labApplications.id, { onDelete: "cascade" }),
    purpose: text().notNull(),
    tokenHash: text().notNull(),
    createdAt: timestamp({ withTimezone: true }).notNull(),
  },
  (table) => [
    primaryKey({ columns: [table.applicationId, table.purpose] }),
    unique("lab_application_tokens_token_hash_key").on(table.tokenHash),
    check("lab_application_tokens_purpose", oneOf("purpose", TOKEN_PURPOSES)),
    check(
      "lab_application_tokens_token_hash",
      matches("token_hash", TOKEN_HASH_PATTERN)
    ),
  ]
)

// A processor asks the applicant to change something; at most one stays open.
export const labApplicationChangeRequests = pgTable(
  "lab_application_change_requests",
  {
    id: uuid().defaultRandom().primaryKey(),
    applicationId: uuid()
      .notNull()
      .references(() => labApplications.id, { onDelete: "cascade" }),
    note: text(),
    requestedBy: uuid().references(() => user.id, { onDelete: "set null" }),
    requestedAt: timestamp({ withTimezone: true }).notNull(),
    dueAt: timestamp({ withTimezone: true }).notNull(),
    closedAt: timestamp({ withTimezone: true }),
  },
  (table) => [
    check(
      "lab_application_change_requests_due_after_request",
      sql`${table.dueAt} > ${table.requestedAt}`
    ),
    index("lab_application_change_requests_application").on(
      table.applicationId
    ),
    uniqueIndex("lab_application_change_requests_open")
      .on(table.applicationId)
      .where(sql`${table.closedAt} is null`),
    index("lab_application_change_requests_due")
      .on(table.dueAt)
      .where(sql`${table.closedAt} is null`),
  ]
)

