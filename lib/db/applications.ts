// The account-creation run of an accepted application.
export const labApplicationProvisioning = pgTable(
  "lab_application_provisioning",
  {
    applicationId: uuid()
      .primaryKey()
      .references(() => labApplications.id, { onDelete: "cascade" }),
    attempts: integer().notNull().default(0),
    nextAt: timestamp({ withTimezone: true }).notNull(),
    error: text(),
    blockedAt: timestamp({ withTimezone: true }),
    startedAt: timestamp({ withTimezone: true }).notNull(),
    finishedAt: timestamp({ withTimezone: true }),
    releasedAt: timestamp({ withTimezone: true }),
  },
  (table) => [
    check("lab_application_provisioning_attempts", sql`${table.attempts} >= 0`),
    check(
      "lab_application_provisioning_finished_unblocked",
      sql`${table.finishedAt} is null or ${table.blockedAt} is null`
    ),
    check(
      "lab_application_provisioning_released_finished",
      sql`${table.releasedAt} is null or ${table.finishedAt} is not null`
    ),
    index("lab_application_provisioning_due")
      .on(table.nextAt)
      .where(sql`${table.blockedAt} is null and ${table.releasedAt} is null`),
  ]
)

export const labApplicationProvisionSteps = pgTable(
  "lab_application_provision_steps",
  {
    applicationId: uuid()
      .notNull()
      .references(() => labApplicationProvisioning.applicationId, {
        onDelete: "cascade",
      }),
    step: text().notNull(),
    completedAt: timestamp({ withTimezone: true }).notNull(),
  },
  (table) => [
    primaryKey({ columns: [table.applicationId, table.step] }),
    check("lab_application_provision_steps_step", oneOf("step", STEP_NAMES)),
  ]
)

// The timeline shown to processors; never holds more than what changed.
export const labApplicationEvents = pgTable(
  "lab_application_events",
  {
    id: bigint({ mode: "number" }).primaryKey().generatedAlwaysAsIdentity(),
    applicationId: uuid()
      .notNull()
      .references(() => labApplications.id, { onDelete: "cascade" }),
    actorKind: text().notNull(),
    actorId: uuid().references(() => user.id, { onDelete: "set null" }),
    kind: text().notNull(),
    changes: jsonb().$type<Record<string, unknown>>(),
    createdAt: timestamp({ withTimezone: true }).notNull(),
  },
  (table) => [
    check(
      "lab_application_events_actor_kind",
      oneOf("actor_kind", ACTOR_KINDS)
    ),
    check("lab_application_events_kind", oneOf("kind", EVENT_KINDS)),
    check(
      "lab_application_events_actor",
      sql`${table.actorKind} = 'admin' or ${table.actorId} is null`
    ),
    index("lab_application_events_timeline").on(table.applicationId, table.id),
  ]
)

